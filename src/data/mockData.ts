// Deterministic 128-dimensional embedding generator for sample profiles
function generateDeterministicEmbedding(seed: number): number[] {
  const vec: number[] = [];
  for (let i = 0; i < 128; i++) {
    const val = Math.sin(seed * 11 + i * 3.7) * 0.5 + Math.cos(seed * 7 - i * 2.3) * 0.5;
    vec.push(val);
  }
  let sumSq = 0;
  for (const v of vec) sumSq += v * v;
  const norm = Math.sqrt(sumSq) || 1;
  return vec.map((v) => v / norm);
}

